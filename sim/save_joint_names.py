"""Write the robot's joints, actuators, sites and cameras (from scene/library.xml) into NOTES.md.

Re-run after changing the robot or the scene generator.
Usage (project root, venv active):
    python sim/save_joint_names.py
"""
import json
from pathlib import Path

import mujoco

ROOT = Path(__file__).resolve().parent.parent
PATH = ROOT / "scene/library.xml"
model = mujoco.MjModel.from_xml_path(str(PATH))
meta = json.loads((ROOT / "scene/library_meta.json").read_text())["robot"]

JOINT_TYPES = {0: "free", 1: "ball", 2: "slide", 3: "hinge"}
base = model.body("base").id
robot_bodies = {b for b in range(model.nbody) if model.body_rootid[b] == base}


def name(obj, i):
    return mujoco.mj_id2name(model, obj, i) or f"(unnamed {i})"


lines = ["# Robot notes", "",
         f"Generated by `sim/save_joint_names.py` from `{PATH.relative_to(ROOT).as_posix()}`. "
         "Books (free joints) and furniture are not listed.", "",
         "Base qpos is the world pose (x, y, yaw) thanks to joint `ref`; base actuators are "
         "velocity servos (world frame, see `Robot.send_cmd_vel`). Arm actuators are position servos.", ""]

lines += ["## Joints", "", "| id | name | type | range (rad or m) | qpos index |", "|---|---|---|---|---|"]
for i in range(model.njnt):
    if model.jnt_bodyid[i] not in robot_bodies:
        continue
    lo, hi = model.jnt_range[i]
    rng = f"{lo:.4f} to {hi:.4f}" if model.jnt_limited[i] else "unlimited"
    lines.append(f"| {i} | {name(mujoco.mjtObj.mjOBJ_JOINT, i)} | "
                 f"{JOINT_TYPES[int(model.jnt_type[i])]} | {rng} | {model.jnt_qposadr[i]} |")

lines += ["", "## Actuators (data.ctrl)", "", "| id | name | kind | ctrl range |", "|---|---|---|---|"]
for i in range(model.nu):
    lo, hi = model.actuator_ctrlrange[i]
    kind = "velocity" if name(mujoco.mjtObj.mjOBJ_ACTUATOR, i).startswith("base_") else (
        "gripper (0 closed .. 255 open = 8 cm)" if i == model.actuator(meta["gripper_actuator"]).id else "position")
    lines.append(f"| {i} | {name(mujoco.mjtObj.mjOBJ_ACTUATOR, i)} | {kind} | {lo:.4f} to {hi:.4f} |")

lines += ["", "## Sites and cameras", ""]
lines += [f"- site `{name(mujoco.mjtObj.mjOBJ_SITE, i)}`" for i in range(model.nsite)
          if model.site_bodyid[i] in robot_bodies]
lines += [f"- camera `{name(mujoco.mjtObj.mjOBJ_CAMERA, i)}` (fovy {model.cam_fovy[i]:.0f} deg)"
          for i in range(model.ncam) if model.cam_bodyid[i] in robot_bodies]

lines += ["", "## Keyframes, tendons, grasp welds", ""]
lines += [f"- keyframe `{name(mujoco.mjtObj.mjOBJ_KEY, i)}`" for i in range(model.nkey)]
lines += [f"- tendon `{name(mujoco.mjtObj.mjOBJ_TENDON, i)}`" for i in range(model.ntendon)]
welds = [name(mujoco.mjtObj.mjOBJ_EQUALITY, i) for i in range(model.neq)
         if name(mujoco.mjtObj.mjOBJ_EQUALITY, i).startswith("grasp_")]
lines.append(f"- {len(welds)} inactive grasp welds `grasp_<book id>` (hand <-> book, see `Robot.attach`)")

lines += ["", "## Poses", "",
          f"- arm home: `{meta['arm_home']}`",
          f"- arm stow (for driving): `{meta['arm_stow']}`",
          f"- arm mount: {meta['mount_x']} m ahead of the base centre, {meta['mount_height']} m high", "",
          "## Totals (robot only)", "",
          f"- joints: {sum(model.jnt_bodyid[i] in robot_bodies for i in range(model.njnt))}",
          f"- actuators: {model.nu}",
          f"- bodies: {len(robot_bodies)}", ""]

(ROOT / "NOTES.md").write_text("\n".join(lines), encoding="utf-8")
print("Saved NOTES.md\n")
print("\n".join(lines))
